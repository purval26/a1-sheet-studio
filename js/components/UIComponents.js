/**
 * Creates a minimal modern slider row with label, value badge, and micro-stepper buttons
 */
export function createSliderControl({ id, label, value, min, max, step = 1, unit = 'mm', onChange }) {
  const container = document.createElement('div');
  container.className = 'space-y-1.5';

  const header = document.createElement('div');
  header.className = 'flex items-center justify-between text-xs';
  header.innerHTML = `
    <span class="text-[var(--text-muted)] font-medium">${label}</span>
    <span id="${id}-badge" class="font-mono text-[var(--text-main)] bg-[var(--bg-tertiary)] px-2 py-0.5 rounded text-[11px] border border-[var(--border-subtle)]">${value} ${unit}</span>
  `;

  const sliderRow = document.createElement('div');
  sliderRow.className = 'flex items-center gap-2';

  const minusBtn = document.createElement('button');
  minusBtn.type = 'button';
  minusBtn.className = 'w-7 h-7 sm:w-8 sm:h-8 flex items-center justify-center rounded-lg bg-[var(--bg-tertiary)] text-[var(--text-muted)] hover:text-[var(--text-main)] hover:bg-[var(--border-subtle)] transition border border-[var(--border-subtle)] touch-manipulation flex-shrink-0';
  minusBtn.innerHTML = Icons.Minus;
  minusBtn.title = 'Decrease';

  const slider = document.createElement('input');
  slider.type = 'range';
  slider.id = id;
  slider.min = min;
  slider.max = max;
  slider.step = step;
  slider.value = value;
  slider.className = 'minimal-slider flex-1 touch-manipulation py-2';

  const plusBtn = document.createElement('button');
  plusBtn.type = 'button';
  plusBtn.className = 'w-7 h-7 sm:w-8 sm:h-8 flex items-center justify-center rounded-lg bg-[var(--bg-tertiary)] text-[var(--text-muted)] hover:text-[var(--text-main)] hover:bg-[var(--border-subtle)] transition border border-[var(--border-subtle)] touch-manipulation flex-shrink-0';
  plusBtn.innerHTML = Icons.Plus;
  plusBtn.title = 'Increase';

  const updateValue = (newVal) => {
    const clamped = Math.min(max, Math.max(min, Number(newVal)));
    slider.value = clamped;
    const badge = container.querySelector(`#${id}-badge`);
    if (badge) badge.textContent = `${clamped} ${unit}`;
    onChange(clamped);
  };

  slider.addEventListener('input', (e) => updateValue(e.target.value));
  minusBtn.addEventListener('click', () => updateValue(Number(slider.value) - step));
  plusBtn.addEventListener('click', () => updateValue(Number(slider.value) + step));

  sliderRow.appendChild(minusBtn);
  sliderRow.appendChild(slider);
  sliderRow.appendChild(plusBtn);

  container.appendChild(header);
  container.appendChild(sliderRow);

  return container;
}

/**
 * Creates a modern segmented pill control
 */
export function createSegmentedControl({ items, activeValue, onChange }) {
  const container = document.createElement('div');
  container.className = 'segmented-control';

  items.forEach((item) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = `segmented-item ${item.value === activeValue ? 'active' : ''}`;
    btn.textContent = item.label;
    btn.dataset.value = item.value;

    btn.addEventListener('click', () => {
      container.querySelectorAll('.segmented-item').forEach((b) => b.classList.remove('active'));
      btn.classList.add('active');
      onChange(item.value);
    });

    container.appendChild(btn);
  });

  return container;
}
